"""Generate checked-in WOFF2 files; see docs/fonts.md for the pinned sources."""

import argparse
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent


def source_characters():
    # Include script strings (theme controls, etc.) and future edits, not just HTML.
    files = sorted((ROOT / "src/pages").rglob("*.astro"))
    files += sorted((ROOT / "src/scripts").rglob("*.js"))
    return set(chr(cp) for cp in range(32, 127)) | {
        char for path in files for char in path.read_text() if not char.isspace()
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gen-directory", type=Path, required=True)
    parser.add_argument("--zen-font", type=Path, required=True)
    args = parser.parse_args()
    output = ROOT / "public/fonts"
    output.mkdir(parents=True, exist_ok=True)
    body = "".join(sorted(source_characters()))
    logo = "".join(sorted(set("タカハシタカユキのポートフォリオ ")))
    definitions = [
        ("gen", "Gen Interface JP", weight, args.gen_directory / f"GenInterfaceJP-{name}.ttf", body)
        for weight, name in [(300, "Light"), (400, "Regular"), (500, "Medium"), (700, "Bold")]
    ] + [("zen", "Zen Kaku Gothic New", 400, args.zen_font, logo)]
    faces, css = [], []
    for slug, family, weight, source, text in definitions:
        font = TTFont(source, recalcTimestamp=False)
        missing = set(map(ord, text)) - font.getBestCmap().keys()
        if missing:
            raise ValueError(f"{family}: unsupported characters {sorted(map(chr, missing))}")
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        # Keep standard shaping/kerning; omit unused discretionary/vertical alternates.
        options.layout_languages = ["dflt", "JAN "]
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(text=text)
        subsetter.subset(font)
        font.flavor = "woff2"
        import io
        buffer = io.BytesIO()
        font.save(buffer)
        data = buffer.getvalue()
        digest = hashlib.sha256(data).hexdigest()
        filename = f"{slug}-{weight}-{digest[:12]}.woff2"
        (output / filename).write_bytes(data)
        faces.append({
            "family": family, "weight": weight, "url": f"/fonts/{filename}",
            "bytes": len(data), "sha256": digest,
            "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "text": text,
            "preload": slug == "zen" or weight in (300, 400),
        })
        css.append(f'''@font-face {{
  font-family: "{family}";
  font-style: normal;
  font-weight: {weight};
  font-display: block;
  src: url("/fonts/{filename}") format("woff2");
}}''')
        print(f"{filename}: {len(data):,} bytes, {len(text)} characters")
    manifest = ROOT / "src/config/fonts.json"
    previous = json.loads(manifest.read_text())["faces"] if manifest.exists() else []
    (ROOT / "src/styles/fonts.css").write_text("/* Generated by scripts/subset-fonts.py. */\n" + "\n".join(css) + "\n")
    manifest.write_text(json.dumps({"faces": faces}, ensure_ascii=False, indent=2) + "\n")
    current = {face["url"] for face in faces}
    for face in previous:
        if face["url"] not in current:
            old = ROOT / "public" / face["url"].lstrip("/")
            if old.parent == output and old.suffix == ".woff2":
                old.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
